    init() throws {
        container = try PersistenceController.getTestingContainer()
        repository = FlashcardRepository(container: container)

        let articles = Self.getSampleArticles()
        sampleArticles = articles
        sampleFlashcards = Self.getSampleFlashcards(linkedTo: articles)
    }
    
    // MARK: Test data helpers

    /// Builds the sample articles that ``getSampleFlashcards(linkedTo:)`` links back to. The three
    /// articles (Alpha, Bravo, Charlie) mirror the corresponding entries in
    /// ``ArticleRepositoryTests/getSampleArticles()`` so the bodies match the sentences the
    /// flashcards lift. Each article's `id` is taken from ``articleIds`` at the matching index, so
    /// `result[i].id == articleIds[i]`. Tags, authors, and timestamps are regenerated on each call;
    /// the IDs stay stable. Not persisted — a test that needs the articles in storage saves them
    /// via ``ArticleRepository`` itself.
