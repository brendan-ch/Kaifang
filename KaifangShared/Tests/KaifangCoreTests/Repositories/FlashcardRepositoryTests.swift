                datePublished: Date(timeIntervalSince1970: 1_700_000_000),
                dateRead: nil,
                tags: [newsTag],
                authors: [author1],
                dateCreated: nowReference.addingTimeInterval(createdOffsets[0]),
                dateModified: nowReference.addingTimeInterval(modifiedOffsets[0])
