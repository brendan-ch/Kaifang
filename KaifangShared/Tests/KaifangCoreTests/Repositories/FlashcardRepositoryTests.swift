            Article(
                id: articleIds[1],
                plainText: "研究團隊在會議上展示了穩定的 quantum 量子處理器原型。新架構顯著提升了運算性能與糾錯能力。論文已於本週正式發表。",
                title: "Bravo: Quantum 量子計算重大突破",
                datePublished: Date(timeIntervalSince1970: 1_710_000_000),
                dateRead: Date(timeIntervalSince1970: 1_715_000_000),
                tags: [newsTag, techTag, cultureTag],
                authors: [author1, author2],
                dateCreated: nowReference.addingTimeInterval(createdOffsets[1]),
                dateModified: nowReference.addingTimeInterval(modifiedOffsets[1])
            ),
            // Charlie (articleIds[2]) — culture/festival, TC body, unpublished + unread, co-authored.
            Article(
                id: articleIds[2],
                plainText: "傳統 dance 舞蹈與街頭藝術在開幕表演中亮相。藝術家們吸引了大批熱情的觀眾。活動將持續整整三天。",
