        let nowReference = Date()
        let createdOffsets: [TimeInterval] = [-3.0, -2.0, -1.0]
        let modifiedOffsets: [TimeInterval] = [-0.003, -0.002, -0.001]

        return [
            // Alpha (articleIds[0]) — transit/news, SC body, unread, single author.
            Article(
                id: articleIds[0],
                plainText: "市议会一致通过新型 buses 巴士拨款议案。该决议将覆盖整个 region 城区的公共交通时间表。下周起新线路开始试运营。",
