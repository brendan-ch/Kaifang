    struct SortCase: Sendable {
        let name: String
        let sortBy: @Sendable (Article, Article) -> Bool
        let criteria: SortCriteria
    }
    
    @Test(
        "Sorting criteria meets expected expected sort orders",
        arguments: [
            SortCase(
                name: "Sorting by article title orders from A to Z",
                sortBy: { $0.title.localizedCompare($1.title) == .orderedAscending },
                criteria: .title(.forward)
            ),
            SortCase(
                name: "Sorting by article title orders from Z to A",
                sortBy: { $0.title.localizedCompare($1.title) == .orderedDescending },
                criteria: .title(.reverse)
            ),
            SortCase(
                name: "Sorting by date modified orders from earliest to latest",
                sortBy: { $0.dateModified < $1.dateModified },
                criteria: .dateModified(.forward)
            ),
            SortCase(
                name: "Sorting by date modified orders from latest to earliest",
                sortBy: { $0.dateModified > $1.dateModified },
                criteria: .dateModified(.reverse)
            ),
            SortCase(
                name: "Sorting by date created orders from earliest to latest",
                sortBy: { $0.dateCreated < $1.dateCreated },
                criteria: .dateCreated(.forward)
            ),
            SortCase(
                name: "Sorting by date created orders from latest to earliest",
                sortBy: { $0.dateCreated > $1.dateCreated },
                criteria: .dateCreated(.reverse)
            ),
        ]
    )
    func sortingCriteriaMeetsExpectedSortOrders(sortCase: SortCase) async throws {
        let expectedArticles = try await generateSavedExpectedArticles().sorted(by: sortCase.sortBy)
        
        let filterArgs = FilterArguments(
            tags: nil,
            titleAndContents: nil,
            unreadOnly: nil
        )
        let sortArg = sortCase.criteria
        
        let resultingArticles = try await repository.list(
            filterBy: filterArgs,
            sortBy: sortArg
        )
        #expect(expectedArticles == resultingArticles)
    }
    
