    // MARK: Filtering and sorting
    
    // note that tag filter tests require a different shape than title/content filters, since
    // tags are their own data entity
    
    @Test(
        "Filtering filters by tags",
        arguments: [
            "News",
            "Tech",
            "Culture"
        ]
    )
    func filterFiltersByTags(
        tagName: String
    ) async throws {
        let expectedArticles = try await generateSavedExpectedArticles().filter {
            $0.tags.contains {
                $0.name.localizedStandardCompare(tagName) == .orderedSame
            }
        }.sorted {
            $0.title < $1.title
        }
        try #require(expectedArticles.count > 0)
        
        let tags = try await repository.getTags()
        let tag = tags.first { $0.name.localizedStandardCompare(tagName) == .orderedSame }
        try #require(tag != nil)
        
        let filterArgs = FilterArguments(
            tags: Set([tag!]),
            titleAndContents: nil,
            unreadOnly: nil
        )
        let sortArg: SortCriteria = .title(.forward)
        
        let resultingArticles = try await repository.list(
            filterBy: filterArgs,
            sortBy: sortArg
        )
        #expect(expectedArticles == resultingArticles)
    }
    
    @Test(
        "Filtering title/contents filters by title and content, with case insensitivity",
        arguments: ["weekend", "region", "Markets", "liquidity", "Festival", "dance"]
    )
    func filterByTitleAndContentsFiltersTitleAndContents(keyword: String) async throws {
        let expectedArticles = try await generateSavedExpectedArticles().filter {
            $0.title.localizedCaseInsensitiveContains(keyword) || $0.plainText.localizedCaseInsensitiveContains(keyword)
        }.sorted {
            $0.title < $1.title
        }
        try #require(expectedArticles.count > 0)
        
        let filterArgs = FilterArguments(
            tags: nil,
            titleAndContents: keyword,
            unreadOnly: nil
        )
        
        let resultingArticles = try await repository.list(
            filterBy: filterArgs,
            sortBy: getDefaultSortCriteria()
        )
        #expect(expectedArticles == resultingArticles)
    }
    
    @Test("Filtering by unread only filters out read articles")
    func filterByUnreadOnlyFiltersOutReadArticles() async throws {
        let expectedArticles = try await generateSavedExpectedArticles().filter {
            $0.dateRead != nil
        }.sorted {
            $0.title < $1.title
        }
        try #require(expectedArticles.count > 0)
        
        let filterArgs = FilterArguments(
            tags: nil,
            titleAndContents: nil,
            unreadOnly: true  // false is same behavior as nil
        )
        
        let resultingArticles = try await repository.list(
            filterBy: filterArgs,
            sortBy: getDefaultSortCriteria()
        )
        #expect(expectedArticles == resultingArticles)
    }
    
